export const getLanguageLocale = (language) => (language === 'en' ? 'en-US' : 'es-ES');

export const translate = (language, key, variables = {}) => {
    const translation = translations[language]?.[key] ?? translations[DEFAULT_LANGUAGE][key];

    if (typeof translation === 'function') {
        return translation(variables);
    }

    return translation ?? key;
};

